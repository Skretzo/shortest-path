package shortestpath.pathfinder;

import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.doReturn;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.*;
import net.runelite.api.*;
import net.runelite.api.gameval.DBTableID;
import net.runelite.api.gameval.InventoryID;
import org.junit.Assume;
import org.junit.Test;
import shortestpath.TestShortestPathConfig;
import shortestpath.WorldPointUtil;
import shortestpath.pathfinder.astar.*;
import shortestpath.requirement.PreferredBanks;
import shortestpath.settings.TeleportationItem;

/**
 * Writes {@code bank-teleports.tsv}: each bank's cheapest route from anywhere, which has to start
 * with a teleport, and that teleport. Every quest, skill and item counts as had, so the costs
 * describe the game rather than one player. Run it after transport or bank changes:
 *
 * <pre>BANK_TELEPORTS_REGEN=1 ./gradlew test --tests '*BankTeleportsGenerator' --rerun</pre>
 */
public class BankTeleportsGenerator
{
	private static final String REGEN_VARIABLE = "BANK_TELEPORTS_REGEN";
	private static final Path FILE = Paths.get("src", "main", "resources", "bank-teleports.tsv");
	/** No walkable land nearby and outside the wilderness, so a route can only start with a teleport. */
	private static final int NOWHERE = WorldPointUtil.packWorldPoint(0, 0, 0);

	@Test
	public void regenerate() throws IOException
	{
		Assume.assumeTrue(REGEN_VARIABLE + " is not set", "1".equals(System.getenv(REGEN_VARIABLE)));
		RoutingStatic stat = TestWorldData.routingStatic();
		PathfinderConfig config = config();
		PreparedRoutingAccount account = config.prepareAStarRoutingAccount(true);
		SiteGraph graph = new SiteGraph(stat, account);
		// The header first and the note padded to its columns, as the TSV lints read them.
		List<String> lines = new ArrayList<>(List.of("# Bank\tCost\tTeleport",
			"# Generated by BankTeleportsGenerator; regenerate with " + REGEN_VARIABLE + "=1 ./gradlew test "
				+ "--tests '*BankTeleportsGenerator' --rerun\t\t"));
		for (String name : PreferredBanks.NAMES)
		{
			// Only the tiles routing banks at.
			int[] tiles = PreferredBanks.tiles(Set.of(name)).stream()
				.filter(tile -> stat.siteIndex(tile) >= 0 && account.bankAccessible(tile))
				.mapToInt(Integer::intValue).sorted().toArray();
			if (tiles.length == 0) continue;
			AStarForwardSearch.Result route = PreparedTarget.prepare(graph, config.getMap(), tiles).search(NOWHERE,
				() -> false, 1, SearchRestrictions.none(), AStarForwardSearch.NO_PROGRESS, (tile, banked) -> true,
				StartOverlay.of(stat, config.getMap(), NOWHERE));
			if (!route.reached()) continue;
			// The item or spell alone: "Amulet of glory: Edgeville" beside Edgeville says the bank twice.
			String teleport = route.path().stream().filter(step -> step.getTransport() != null).findFirst()
				.orElseThrow().getTransport().getDisplayInfo().split(": ", 2)[0];
			lines.add(name + "\t" + route.cost() + "\t" + teleport);
		}
		Files.write(FILE, (String.join("\n", lines) + "\n").getBytes(StandardCharsets.UTF_8));
		System.err.println(REGEN_VARIABLE + " active - rewrote " + FILE);
	}

	/** Every quest finished, every skill 99, every varbit met, and every teleport item owned bar one. */
	private static PathfinderConfig config()
	{
		Client client = mock(Client.class);
		ItemContainer empty = mock(ItemContainer.class);
		when(client.getGameState()).thenReturn(GameState.LOGGED_IN);
		when(client.getClientThread()).thenReturn(Thread.currentThread());
		when(client.getDBTableRows(DBTableID.Quest.ID)).thenReturn(List.of());
		when(client.getBoostedSkillLevel(any(Skill.class))).thenReturn(99);
		doReturn(new Item[0]).when(empty).getItems();
		doReturn(empty).when(client).getItemContainer(InventoryID.INV);
		doReturn(empty).when(client).getItemContainer(InventoryID.WORN);
		TestShortestPathConfig settings = new TestShortestPathConfig();
		settings.set("currencyThreshold", 10000000);
		settings.set("useTeleportationItems", TeleportationItem.ALL);
		// The Dorgesh-kaan sphere lands at a random spot in the city, not the one tile its row gives.
		settings.setBlockedTeleportItemsValue("10972");
		PathfinderConfig config = new TestPathfinderConfig(client, settings, QuestState.FINISHED, true, true);
		config.refresh();
		return config;
	}
}
