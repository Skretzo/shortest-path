package shortestpath.requirement;

import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

import lombok.extern.slf4j.Slf4j;
import shortestpath.WorldPointUtil;
import shortestpath.transport.ResourceLoader;
import shortestpath.transport.TransportType;
import shortestpath.transport.parser.TransportRecord;

/**
 * Per-item teleport restriction support: the family map the config panel's
 * restriction checklist groups by, plus the CSV contract shared by the hidden
 * {@code blockedTeleportItems} config key.
 *
 * <p>
 * The '#'-category headers in {@code teleportation_items.tsv} are comments that
 * {@link shortestpath.transport.parser.TsvParser} skips at runtime, so the
 * grouping is materialized as its own bundled resource
 * ({@code /transports/teleport_restrictions.tsv}) generated by
 * {@code scripts/generate_teleport_restrictions.py}. Every numeric item id in
 * the source TSV belongs to exactly one family; {@code teleportation_boxes.tsv}
 * carries no {@code Items} column and is out of scope for id-keyed blocking.
 * </p>
 *
 * <p>
 * CSV contract: a comma-separated list where a bare {@code id} record blocks
 * the item and an {@code id:N} record sets a per-item threshold override of N
 * tiles. Unknown or malformed entries are skipped with a warning — user- or
 * profile-authored CSV must never break {@code refresh()} or panel
 * construction. Empty string means "no restrictions" (the default).
 * </p>
 */
@Slf4j
public final class TeleportRestriction
{
	private TeleportRestriction()
	{
	}

	/**
	 * The transport types whose item requirements are player-restrictable:
	 * per-item blocks and threshold overrides only consult these. Other types
	 * (boats, agility shortcuts, POH teleports, …) keep item requirements as
	 * pure inventory constraints.
	 */
	public static boolean isItemTeleportType(TransportType type)
	{
		return TransportType.TELEPORTATION_ITEM.equals(type)
			|| TransportType.SEASONAL_TRANSPORTS.equals(type)
			|| TransportType.QUETZAL_WHISTLE.equals(type);
	}

	/**
	 * A named group of teleportation item ids. {@code displayItemId} is the
	 * family's representative item (used for the checklist row icon);
	 * {@code memberItemIds} is the sorted set of raw item ids the family
	 * covers; {@code memberLabels} maps each member id to the display label
	 * harvested from the source TSV's {@code Display info} prefixes — the
	 * variant-match surface for checklist search.
	 */
	public static final class Family
	{
		private final String name;
		private final int displayItemId;
		private final Set<Integer> memberItemIds;
		private final Map<Integer, String> memberLabels;
		private final Map<Integer, String> options;

		public Family(String name, int displayItemId, Set<Integer> memberItemIds,
			Map<Integer, String> memberLabels)
		{
			this(name, displayItemId, memberItemIds, memberLabels, Collections.emptyMap());
		}

		public Family(String name, int displayItemId, Set<Integer> memberItemIds,
			Map<Integer, String> memberLabels, Map<Integer, String> options)
		{
			this.name = name;
			this.displayItemId = displayItemId;
			this.memberItemIds = memberItemIds;
			this.memberLabels = memberLabels;
			this.options = options;
		}

		public String name()
		{
			return name;
		}

		public int displayItemId()
		{
			return displayItemId;
		}

		public Set<Integer> memberItemIds()
		{
			return memberItemIds;
		}

		public Map<Integer, String> memberLabels()
		{
			return memberLabels;
		}

		/**
		 * The family's distinct teleport destinations as a packed-destination
		 * → label map in first-seen order. Labels come straight from the
		 * source TSV's {@code Display info} cells (the tail after the first
		 * {@code ':'}, or the whole cell when it carries no {@code ':'}) —
		 * the checkbox's display string is data, so a bad label is repaired
		 * in {@code teleportation_items.tsv}, not in code. A family whose
		 * serving rows all reach one destination yields a single entry.
		 */
		public Map<Integer, String> options()
		{
			return options;
		}
	}

	/**
	 * The option derivation's two products: the per-family option maps the
	 * panel renders (canonical destination → label) and the rep →
	 * member-destination → group-destinations expansion index that resolves
	 * {@code rep@dest} records back to whole option groups. Both are derived
	 * in the same pass so they can never disagree about group membership.
	 */
	private static final class DerivedOptions
	{
		private final List<ResourceLoader.RestrictionFamilyRow> rows;
		private final List<Map<Integer, String>> options;
		private final Map<Integer, Map<Integer, Set<Integer>>> expansion;

		DerivedOptions(List<ResourceLoader.RestrictionFamilyRow> rows,
			List<Map<Integer, String>> options,
			Map<Integer, Map<Integer, Set<Integer>>> expansion)
		{
			this.rows = rows;
			this.options = options;
			this.expansion = expansion;
		}
	}

	private static volatile DerivedOptions derivedOptionsHolder;

	private static DerivedOptions derivedOptions()
	{
		DerivedOptions derived = derivedOptionsHolder;
		if (derived == null)
		{
			synchronized (TeleportRestriction.class)
			{
				derived = derivedOptionsHolder;
				if (derived == null)
				{
					derived = deriveOptions(ResourceLoader.families());
					derivedOptionsHolder = derived;
				}
			}
		}
		return derived;
	}

	/**
	 * Loads the bundled family map through {@link ResourceLoader} — the loader
	 * owns the resource read and the row idiom; this entry point maps its raw
	 * rows onto the panel-facing {@link Family} model. Malformed rows are
	 * skipped with a warning (the checklist degrades to fewer rows rather than
	 * crashing); an absent or malformed {@code memberLabels} column degrades
	 * to an empty map for that family, and a missing resource degrades to an
	 * empty list — panel construction must not crash on packaging gaps.
	 */
	public static List<Family> loadFamilies()
	{
		DerivedOptions derived = derivedOptions();
		List<Family> families = new ArrayList<>(derived.rows.size());
		for (int i = 0; i < derived.rows.size(); i++)
		{
			ResourceLoader.RestrictionFamilyRow row = derived.rows.get(i);
			families.add(new Family(row.name(), row.displayItemId(),
				row.memberItemIds(), row.memberLabels(), derived.options.get(i)));
		}
		return Collections.unmodifiableList(families);
	}

	/**
	 * Derives each family's label-keyed option map in one pass over the
	 * bundled {@code teleportation_items.tsv} records, alongside the
	 * rep → destination → option-group expansion index. A record SERVES
	 * every family index its {@code Items} cell contributes a member id to —
	 * a cross-family OR row lands the same destination option in each family
	 * it serves.
	 *
	 * <p>
	 * Option identity is the in-game teleport name: every serving record's
	 * {@code Display info} tail (after the first {@code ':'}; the whole cell
	 * when it carries none; the raw coordinates when the cell is blank) names
	 * the option its {@code Destination} joins. Rows sharing a label collapse
	 * into one option covering all their destinations — varbit- and
	 * skill-gated tile variants of a single menu entry. A destination claimed
	 * by an earlier label never joins a later group: a conflicting label for
	 * an already-seen destination keeps the first label and warns, and a
	 * label left with no destination yields no option. The map key is the
	 * group's canonical (first-seen) destination so {@code rep@dest} records
	 * keep their tile-shaped second half.
	 * </p>
	 */
	private static DerivedOptions deriveOptions(
		List<ResourceLoader.RestrictionFamilyRow> rows)
	{
		Map<Integer, Integer> memberToFamily = new HashMap<>();
		for (int i = 0; i < rows.size(); i++)
		{
			for (int memberId : rows.get(i).memberItemIds())
			{
				Integer previous = memberToFamily.putIfAbsent(memberId, i);
				if (previous != null && !previous.equals(i))
				{
					log.warn("Item id {} claimed by families '{}' and '{}' — '{}' serves it",
						memberId, rows.get(previous).name(), rows.get(i).name(),
						rows.get(previous).name());
				}
			}
		}

		// family index -> option label -> the ordered group of destinations
		// that label claims (first-seen label order); family index ->
		// destination -> owning label (one tile, one option).
		List<Map<String, LinkedHashSet<Integer>>> labelGroups = new ArrayList<>(rows.size());
		List<Map<Integer, String>> claimed = new ArrayList<>(rows.size());
		for (int i = 0; i < rows.size(); i++)
		{
			labelGroups.add(new LinkedHashMap<>());
			claimed.add(new HashMap<>());
		}

		if (!memberToFamily.isEmpty())
		{
			for (TransportRecord record : ResourceLoader.teleportationItemRecords())
			{
				Set<Integer> served = servedFamilyIndexes(record.getItems(), memberToFamily);
				if (served.isEmpty())
				{
					continue;
				}

				int[] destination = parseDestination(record.getDestination());
				if (destination == null)
				{
					log.warn("Skipping teleportation_items row with unparseable Destination '{}'",
						record.getDestination());
					continue;
				}

				int packedDest =
					WorldPointUtil.packWorldPoint(destination[0], destination[1], destination[2]);
				String label = optionLabel(record.getDisplayInfo(), destination);

				for (int familyIdx : served)
				{
					String owner = claimed.get(familyIdx).get(packedDest);
					if (owner != null)
					{
						if (!owner.equals(label))
						{
							log.warn("Conflicting option label for family '{}' destination {} "
								+ "('{}' vs '{}') — keeping the first",
								rows.get(familyIdx).name(), record.getDestination(),
								owner, label);
						}
						continue;
					}
					claimed.get(familyIdx).put(packedDest, label);
					labelGroups.get(familyIdx)
						.computeIfAbsent(label, k -> new LinkedHashSet<>())
						.add(packedDest);
				}
			}
		}

		List<Map<Integer, String>> options = new ArrayList<>(rows.size());
		Map<Integer, Map<Integer, Set<Integer>>> expansion = new HashMap<>();
		for (int i = 0; i < rows.size(); i++)
		{
			Map<Integer, String> familyOptions = new LinkedHashMap<>();
			Map<Integer, Set<Integer>> destToGroup = new HashMap<>();
			for (Map.Entry<String, LinkedHashSet<Integer>> group : labelGroups.get(i).entrySet())
			{
				Set<Integer> groupDests = Collections.unmodifiableSet(group.getValue());
				// The canonical destination is the group's first-seen tile —
				// the key rep@dest records store and expand through.
				familyOptions.put(group.getValue().iterator().next(), group.getKey());
				for (int dest : group.getValue())
				{
					destToGroup.put(dest, groupDests);
				}
			}
			options.add(Collections.unmodifiableMap(familyOptions));
			if (!destToGroup.isEmpty())
			{
				expansion.put(rows.get(i).displayItemId(),
					Collections.unmodifiableMap(destToGroup));
			}
		}

		return new DerivedOptions(rows, Collections.unmodifiableList(options),
			Collections.unmodifiableMap(expansion));
	}

	/**
	 * The family indexes a record's {@code Items} cell serves: every operand's
	 * digit item id is looked up in the member index. Mirrors the
	 * ItemRequirementParser operand grammar in miniature — spaces stripped,
	 * {@code &&}/{@code ||} normalized, operands split on {@code &}/{@code |},
	 * the {@code NAME} side of {@code NAME=qty} taken, {@code UNLOCK_}
	 * prefixes skipped. Non-digit operands warn and skip rather than throw —
	 * this scan never breaks on data.
	 */
	private static Set<Integer> servedFamilyIndexes(String itemsCell,
		Map<Integer, Integer> memberToFamily)
	{
		Set<Integer> served = new LinkedHashSet<>();
		if (itemsCell == null || itemsCell.isEmpty())
		{
			return served;
		}

		String normalized = itemsCell.replace(" ", "")
			.replace("&&", "&")
			.replace("||", "|");
		for (String operand : normalized.split("[&|]"))
		{
			if (operand.isEmpty())
			{
				continue;
			}
			int eq = operand.indexOf('=');
			String name = eq >= 0 ? operand.substring(0, eq) : operand;
			if (name.startsWith("UNLOCK_"))
			{
				continue;
			}
			try
			{
				Integer familyIdx = memberToFamily.get(Integer.parseInt(name));
				if (familyIdx != null)
				{
					served.add(familyIdx);
				}
			}
			catch (NumberFormatException e)
			{
				log.warn("Skipping non-item operand '{}' in Items cell '{}'", name, itemsCell);
			}
		}
		return served;
	}

	/**
	 * Parses a {@code "x y z"} destination cell to its three coordinates;
	 * {@code null} when the cell is missing, blank, or not exactly three
	 * integers.
	 */
	private static int[] parseDestination(String cell)
	{
		if (cell == null || cell.isBlank())
		{
			return null;
		}
		String[] parts = cell.trim().split("\\s+");
		if (parts.length != 3)
		{
			return null;
		}
		try
		{
			return new int[]{
				Integer.parseInt(parts[0]),
				Integer.parseInt(parts[1]),
				Integer.parseInt(parts[2])};
		}
		catch (NumberFormatException e)
		{
			return null;
		}
	}

	/**
	 * The GUI label for one serving row: the {@code Display info} tail after
	 * the first {@code ':'}, the whole trimmed cell when it carries none, or
	 * the raw {@code "x, y, z"} coordinates when the cell (or its tail) is
	 * blank.
	 */
	private static String optionLabel(String displayInfo, int[] destination)
	{
		if (displayInfo != null)
		{
			int colon = displayInfo.indexOf(':');
			String label = colon >= 0
				? displayInfo.substring(colon + 1).trim()
				: displayInfo.trim();
			if (!label.isEmpty())
			{
				return label;
			}
		}
		return destination[0] + ", " + destination[1] + ", " + destination[2];
	}

	/**
	 * Parses the {@code blockedTeleportItems} CSV into a blocked-id set and a
	 * per-item threshold map, discarding any {@code rep@dest} option-block
	 * records. Delegates to the three-output overload so the panel keeps
	 * compiling on the two-output call until the option UI lands.
	 */
	public static void parseBlocked(String csv, Set<Integer> blockedOut, Map<Integer, Integer> thresholdOut)
	{
		parseBlocked(csv, blockedOut, thresholdOut, new HashMap<>());
	}

	/**
	 * Parses the {@code blockedTeleportItems} CSV into a blocked-id set, a
	 * per-item threshold map and a per-family destination-block map.
	 * {@code id} records add to {@code blockedOut}; {@code id:N} records
	 * merge into {@code thresholdOut} keeping the max N per id;
	 * {@code repId@packedDest} records merge into {@code optionBlocksOut} —
	 * the rep id is the family's {@code displayItemId}, so the panel and the
	 * engine share one key space. Malformed entries are skipped with a
	 * warning; this method never throws on user-authored input.
	 */
	public static void parseBlocked(String csv, Set<Integer> blockedOut,
		Map<Integer, Integer> thresholdOut, Map<Integer, Set<Integer>> optionBlocksOut)
	{
		if (csv == null || csv.isBlank())
		{
			return;
		}

		for (String rawEntry : csv.split(","))
		{
			String entry = rawEntry.trim();
			if (entry.isEmpty())
			{
				continue;
			}

			try
			{
				int at = entry.indexOf('@');
				if (at >= 0)
				{
					// Destination-scoped option block: rep@packedDest. Entries
					// never legitimately contain '@' elsewhere — require
					// exactly two int-parseable parts. The rep is an item id
					// and cannot be negative; the destination can — packed
					// world points at plane >= 2 set the sign bit.
					String[] parts = entry.split("@", -1);
					if (parts.length != 2)
					{
						throw new NumberFormatException("expected rep@dest");
					}
					int rep = Integer.parseInt(parts[0].trim());
					int dest = Integer.parseInt(parts[1].trim());
					if (rep < 0)
					{
						throw new NumberFormatException("negative rep id");
					}
					optionBlocksOut.computeIfAbsent(rep, k -> new HashSet<>()).add(dest);
					continue;
				}

				int colon = entry.indexOf(':');
				if (colon < 0)
				{
					int id = Integer.parseInt(entry);
					if (id < 0)
					{
						throw new NumberFormatException("negative id");
					}
					blockedOut.add(id);
				}
				else
				{
					int id = Integer.parseInt(entry.substring(0, colon).trim());
					int threshold = Integer.parseInt(entry.substring(colon + 1).trim());
					if (id < 0 || threshold < 0)
					{
						throw new NumberFormatException("negative id or threshold");
					}
					thresholdOut.merge(id, threshold, Math::max);
				}
			}
			catch (NumberFormatException e)
			{
				log.warn("Skipping malformed blockedTeleportItems entry: {}", entry);
			}
		}
	}

	/**
	 * Serializes a blocked-id set and threshold map back to the CSV contract,
	 * dropping any option blocks. Delegates to the three-input overload.
	 */
	public static String toCsv(Set<Integer> blocked, Map<Integer, Integer> thresholds)
	{
		return toCsv(blocked, thresholds, Map.of());
	}

	/**
	 * Serializes a blocked-id set, threshold map and option-block map back to
	 * the CSV contract: sorted blocked ids first, then sorted {@code id:N}
	 * threshold records, then {@code rep@dest} records sorted by rep then
	 * destination. Empty (or null) inputs produce {@code ""}.
	 */
	public static String toCsv(Set<Integer> blocked, Map<Integer, Integer> thresholds,
		Map<Integer, Set<Integer>> optionBlocks)
	{
		StringBuilder sb = new StringBuilder();

		if (blocked != null)
		{
			List<Integer> ids = new ArrayList<>(blocked);
			Collections.sort(ids);
			for (int id : ids)
			{
				if (sb.length() > 0)
				{
					sb.append(',');
				}
				sb.append(id);
			}
		}

		if (thresholds != null)
		{
			List<Integer> ids = new ArrayList<>(thresholds.keySet());
			Collections.sort(ids);
			for (int id : ids)
			{
				if (sb.length() > 0)
				{
					sb.append(',');
				}
				sb.append(id).append(':').append(thresholds.get(id));
			}
		}

		if (optionBlocks != null)
		{
			List<Integer> reps = new ArrayList<>(optionBlocks.keySet());
			Collections.sort(reps);
			for (int rep : reps)
			{
				List<Integer> dests = new ArrayList<>(optionBlocks.get(rep));
				Collections.sort(dests);
				for (int dest : dests)
				{
					if (sb.length() > 0)
					{
						sb.append(',');
					}
					sb.append(rep).append('@').append(dest);
				}
			}
		}

		return sb.toString();
	}

	/**
	 * The lazily-built memberId → representative (displayItemId) index over
	 * {@link #loadFamilies()}, published through a volatile reference and
	 * built once inside a synchronized holder — the families are static
	 * bundled resources, so one immutable index serves every caller. Two
	 * families claiming the same member id must not happen; if the data ever
	 * drifts there the first family written wins and a warning is logged.
	 */
	private static volatile Map<Integer, Integer> representativeIndexHolder;

	public static Map<Integer, Integer> representativeIndex()
	{
		Map<Integer, Integer> index = representativeIndexHolder;
		if (index == null)
		{
			synchronized (TeleportRestriction.class)
			{
				index = representativeIndexHolder;
				if (index == null)
				{
					index = buildRepresentativeIndex();
					representativeIndexHolder = index;
				}
			}
		}
		return index;
	}

	private static Map<Integer, Integer> buildRepresentativeIndex()
	{
		Map<Integer, Integer> index = new HashMap<>();
		for (Family family : loadFamilies())
		{
			for (int memberId : family.memberItemIds())
			{
				Integer previous = index.putIfAbsent(memberId, family.displayItemId());
				if (previous != null && previous != family.displayItemId())
				{
					log.warn("Item id {} claimed by multiple restriction families "
						+ "('{}' wins)", memberId, family.name());
				}
			}
		}
		return Collections.unmodifiableMap(index);
	}

	/**
	 * The representative (displayItemId) of the family {@code itemId} belongs
	 * to, or a negative value when the id belongs to no restriction family.
	 * The CSV {@code rep@dest} record stores the display id, so panel and
	 * engine share one key space.
	 */
	public static int representativeFor(int itemId)
	{
		return representativeIndex().getOrDefault(itemId, -1);
	}

	/**
	 * The rep → member-destination → option-group-destinations expansion
	 * index derived alongside {@link #loadFamilies()}' option groups. A
	 * {@code rep@dest} record names one option by its canonical destination,
	 * but any member destination resolves to the same group, so a stale
	 * record still blocks the whole option. Unmodifiable; representatives
	 * with no option rows are absent.
	 */
	public static Map<Integer, Map<Integer, Set<Integer>>> optionExpansionIndex()
	{
		return derivedOptions().expansion;
	}

	/**
	 * Maps every recorded destination in {@code optionBlocks} through
	 * {@link #optionExpansionIndex()}, unioning each destination's option
	 * group — one record suppresses every tile variant of the option it
	 * names. Destinations absent from the index pass through as literal
	 * blocked tiles, so a stale {@code blockedTeleportItems} row degrades to
	 * its written destination rather than silently widening. The returned
	 * sets are fresh copies; callers may freeze or mutate them independently
	 * of the index.
	 */
	public static Map<Integer, Set<Integer>> expandOptionDests(
		Map<Integer, Set<Integer>> optionBlocks)
	{
		Map<Integer, Map<Integer, Set<Integer>>> index = optionExpansionIndex();
		Map<Integer, Set<Integer>> expanded = new HashMap<>();
		for (Map.Entry<Integer, Set<Integer>> entry : optionBlocks.entrySet())
		{
			Map<Integer, Set<Integer>> repIndex = index.get(entry.getKey());
			Set<Integer> dests = new LinkedHashSet<>();
			for (int dest : entry.getValue())
			{
				Set<Integer> group = repIndex == null ? null : repIndex.get(dest);
				if (group == null)
				{
					dests.add(dest);
				}
				else
				{
					dests.addAll(group);
				}
			}
			expanded.put(entry.getKey(), dests);
		}
		return expanded;
	}
}
